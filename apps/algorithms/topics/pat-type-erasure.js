const ERASURE = `// Type erasure: Circle and Square share no base class, yet one vector holds
// both, by value. The polymorphism is hidden inside Shape.
#include <concepts>
#include <cstdio>
#include <memory>
#include <type_traits>
#include <vector>

struct Circle { double r; double area() const { return 3.14159265 * r * r; } };
struct Square { double s; double area() const { return s * s; } };

class Shape {
    // The private interface: what Shape needs from whatever it holds.
    struct Concept {
        virtual ~Concept() = default;
        virtual double area() const = 0;
        virtual std::unique_ptr<Concept> clone() const = 0;
    };

    // One Model per held type, generated by the compiler on demand.
    template <class T>
    struct Model final : Concept {
        T obj;
        explicit Model(T o) : obj(std::move(o)) {}
        double area() const override { return obj.area(); }
        std::unique_ptr<Concept> clone() const override { return std::make_unique<Model>(*this); }
    };

    std::unique_ptr<Concept> self_;

public:
    template <class T>
        requires(!std::same_as<std::remove_cvref_t<T>, Shape>)
    Shape(T obj) : self_(std::make_unique<Model<T>>(std::move(obj))) {}

    // Value semantics: copying a Shape copies what it holds.
    Shape(const Shape& o) : self_(o.self_->clone()) {}
    Shape& operator=(const Shape& o) { self_ = o.self_->clone(); return *this; }
    Shape(Shape&&) noexcept = default;
    Shape& operator=(Shape&&) noexcept = default;

    double area() const { return self_->area(); }
};

int main() {
    std::vector<Shape> shapes{Circle{2}, Square{3}};
    for (const Shape& s : shapes) std::printf("area %.2f\\n", s.area());

    Shape copy = shapes[0];          // a deep copy: a second Model<Circle>
    copy = Square{5};                // the copy changes; the original doesn't
    std::printf("original %.2f, copy %.2f\\n", shapes[0].area(), copy.area());
}
`;

const MODERN = `// The standard library's own type erasure. std::function erases "anything
// callable with this signature"; std::any erases "anything copyable".
#include <any>
#include <cstdio>
#include <functional>
#include <string>
#include <vector>

struct Square { int operator()(int x) const { return x * x; } };

int main() {
    std::vector<std::function<int(int)>> fs;
    fs.push_back([](int x) { return x + 1; });          // a lambda
    fs.push_back([k = 10](int x) { return x * k; });    // a lambda with state
    fs.push_back(Square{});                             // a function object
    for (auto& f : fs) std::printf("%d ", f(3));
    std::printf("\\n");

    std::any a = std::string("hello");
    std::printf("any holds a string: %s\\n", std::any_cast<std::string&>(a).c_str());
}
`;

